# ---------------------------------------------------
# Professional Lightroom Slider Scaling
# ---------------------------------------------------

def scale_slider(

    slider_name,

    value
):

    # -----------------------------------------------
    # Exposure
    # Lightroom safe:
    # -5 → +5
    # -----------------------------------------------

    if slider_name == "Exposure":

        return value * 0.015

    # -----------------------------------------------
    # Contrast
    # -----------------------------------------------

    elif slider_name == "Contrast":

        return value * 0.35

    # -----------------------------------------------
    # Highlights
    # -----------------------------------------------

    elif slider_name == "Highlights":

        return value * 0.45

    # -----------------------------------------------
    # Shadows
    # -----------------------------------------------

    elif slider_name == "Shadows":

        return value * 0.40

    # -----------------------------------------------
    # Whites
    # -----------------------------------------------

    elif slider_name == "Whites":

        return value * 0.35

    # -----------------------------------------------
    # Blacks
    # -----------------------------------------------

    elif slider_name == "Blacks":

        return value * 0.30

    # -----------------------------------------------
    # Clarity
    # -----------------------------------------------

    elif slider_name == "Clarity":

        return value * 0.25

    # -----------------------------------------------
    # Texture
    # -----------------------------------------------

    elif slider_name == "Texture":

        return value * 0.20

    # -----------------------------------------------
    # Saturation
    # -----------------------------------------------

    elif slider_name == "Saturation":

        return value * 0.12

    # -----------------------------------------------
    # Vibrance
    # -----------------------------------------------

    elif slider_name == "Vibrance":

        return value * 0.18

    # -----------------------------------------------
    # Temperature
    # -----------------------------------------------

    elif slider_name == "Temperature":

        return value * 0.25

    # -----------------------------------------------
    # Fallback
    # -----------------------------------------------

    return value